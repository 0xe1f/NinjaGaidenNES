#!/usr/bin/env python3
# Write Makefile from NinjaGaiden.asm INCBIN banks and NinjaGaiden.cfg.
# Bank lists are generated. Do not hand-edit PRG_BINS / CHR_BINS.

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASM = ROOT / "NinjaGaiden.asm"
CFG = ROOT / "NinjaGaiden.cfg"
MAKEFILE = ROOT / "Makefile"
ROM = ROOT / "reference" / "gaiden.nes"
STEM = "NinjaGaiden"
MAPPERS = {1: "MMC1"}

INCBIN_RE = re.compile(r'\.incbin\s+"(prg|chr)/bank(\d+)\.bin"')
INCLUDE_RE = re.compile(r'\.include\s+"([^"]+)"')
SEG_RE = re.compile(r"^\s+(PRG|CHR)(\d+):\s+load\b", re.M)
ASM_SEG_RE = re.compile(r'\.segment\s+"(PRG|CHR)(\d+)"')


def _code(line: str) -> str:
    return line.split(";", 1)[0]


def banks_from_asm(text: str, seen: set[Path] | None = None) -> tuple[list[int], list[int]]:
    """INCBIN bank ids, including ones inside .include files. First sighting wins."""
    if seen is None:
        seen = set()
    prg: list[int] = []
    chr_: list[int] = []

    def add(kind: str, num: int) -> None:
        dest = prg if kind == "prg" else chr_
        if num not in dest:
            dest.append(num)

    for line in text.splitlines():
        code = _code(line)
        inc = INCLUDE_RE.search(code)
        if inc:
            path = (ROOT / inc.group(1)).resolve()
            if path not in seen:
                seen.add(path)
                sub_prg, sub_chr = banks_from_asm(path.read_text(), seen)
                for n in sub_prg:
                    add("prg", n)
                for n in sub_chr:
                    add("chr", n)
        for kind, num in INCBIN_RE.findall(code):
            add(kind, int(num))
    return prg, chr_


def segments_from_asm(text: str) -> tuple[list[int], list[int]]:
    prg: list[int] = []
    chr_: list[int] = []
    for line in text.splitlines():
        m = ASM_SEG_RE.search(_code(line))
        if not m:
            continue
        (prg if m.group(1) == "PRG" else chr_).append(int(m.group(2)))
    if not prg:
        raise SystemExit(f"{ASM.name}: no .segment \"PRG#\" lines")
    return prg, chr_


def banks_from_cfg(text: str) -> tuple[list[int], list[int]]:
    prg: list[int] = []
    chr_: list[int] = []
    for kind, num in SEG_RE.findall(text):
        (prg if kind == "PRG" else chr_).append(int(num))
    return prg, chr_


def mapper_name(rom: Path) -> str:
    hdr = rom.read_bytes()[:16]
    if hdr[:4] != b"NES\x1a":
        raise SystemExit(f"{rom} is not an iNES file")
    mapper = (hdr[6] >> 4) | (hdr[7] & 0xF0)
    prg_n, chr_n = hdr[4], hdr[5]
    return MAPPERS.get(mapper, f"mapper {mapper}"), prg_n, chr_n


def _bins_line(kind: str, ids: list[int]) -> str:
    if not ids:
        return f"{kind.upper()}_BINS :="
    names = " ".join(f"{n:02d}" for n in ids)
    return f"{kind.upper()}_BINS := $(patsubst %,{kind}/bank%.bin,{names})"


def includes_from(text: str, seen: set[Path] | None = None) -> list[str]:
    if seen is None:
        seen = set()
    found: list[str] = []
    for line in text.splitlines():
        inc = INCLUDE_RE.search(_code(line))
        if not inc:
            continue
        rel = inc.group(1)
        path = (ROOT / rel).resolve()
        if path in seen:
            continue
        seen.add(path)
        found.append(rel)
        found.extend(includes_from(path.read_text(), seen))
    return found


def render(
    prg: list[int],
    chr_: list[int],
    mapper: str,
    prg_segs: list[int],
    chr_segs: list[int],
    includes: list[str],
) -> str:
    kib = len(prg_segs) * 16 + len(chr_segs) * 8
    prg_bins = _bins_line("prg", prg)
    chr_bins = _bins_line("chr", chr_)
    includes_line = " ".join(includes)
    return f"""# {STEM} (NES, {mapper}, {kib} KiB) disassembly build.
# Generated by tools/gen-makefile.py — do not edit PRG_BINS / CHR_BINS by hand.
#
#   make            assemble {STEM}.asm -> {STEM}.nes
#   make verify     SHA-1 check against {STEM}.sha1
#   make banks      split reference/gaiden.nes into prg/ and chr/ bins
#   make tools      build ca65/ld65 into tools/ (cc65 V2.19)
#   make clean      remove the assembled ROM and object file
#
# Prerequisite: tools/ca65 and tools/ld65 (make tools).
# While banks are still INCBIN, run `make banks` once. Later verifies do not
# need reference/gaiden.nes if the bins are already on disk.

SRC      := {STEM}.asm
CFG      := {STEM}.cfg
OUT      := {STEM}.nes
SHA1FILE := {STEM}.sha1
CA65     ?= tools/ca65
LD65     ?= tools/ld65
ROM      ?= reference/gaiden.nes
SHA1SUM  ?= $(shell command -v sha1sum 2>/dev/null || echo "shasum -a 1")

{prg_bins}
{chr_bins}

.PHONY: all verify clean banks tools

INCLUDES := {includes_line}

all: $(OUT)

$(OUT): $(SRC) $(CFG) $(INCLUDES) $(PRG_BINS) $(CHR_BINS)
	mkdir -p generated
	$(CA65) -o generated/{STEM}.o $(SRC)
	$(LD65) -C $(CFG) -o $(OUT) generated/{STEM}.o

verify: all
	@$(SHA1SUM) -c $(SHA1FILE)

banks: $(ROM) tools/split-rom.py
	python3 tools/split-rom.py $(ROM)

tools:
	tools/install-cc65

clean:
	rm -f $(OUT)
	rm -rf generated
"""


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate Makefile from INCBIN banks")
    parser.add_argument("--check", action="store_true", help="exit 1 if Makefile is stale")
    args = parser.parse_args()

    asm = ASM.read_text()
    cfg = CFG.read_text()
    prg_segs, chr_segs = segments_from_asm(asm)
    prg, chr_ = banks_from_asm(asm)
    cfg_prg, cfg_chr = banks_from_cfg(cfg)
    if prg_segs != cfg_prg or chr_segs != cfg_chr:
        raise SystemExit(
            "asm segments and cfg segments differ: "
            f"asm PRG {prg_segs} CHR {chr_segs}; cfg PRG {cfg_prg} CHR {cfg_chr}"
        )
    mapper = "MMC1"
    if ROM.is_file():
        mapper, prg_n, chr_n = mapper_name(ROM)
        if prg_n != len(prg_segs) or chr_n != len(chr_segs):
            raise SystemExit(
                f"{ROM.name} has {prg_n} PRG / {chr_n} CHR units; "
                f"asm has {len(prg_segs)} / {len(chr_segs)} segments"
            )
    elif "MMC1" not in asm:
        mapper = "iNES"
    text = render(prg, chr_, mapper, prg_segs, chr_segs, includes_from(asm))
    if args.check:
        if not MAKEFILE.is_file() or MAKEFILE.read_text() != text:
            raise SystemExit(f"{MAKEFILE.name} is stale; run tools/gen-makefile.py")
        print(f"{MAKEFILE.name} matches")
        return
    MAKEFILE.write_text(text)
    print(f"wrote {MAKEFILE.name}: {len(prg)} PRG, {len(chr_)} CHR")


if __name__ == "__main__":
    main()
