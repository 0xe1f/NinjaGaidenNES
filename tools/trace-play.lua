local logf = io.open(OUT, "w")

local function log(msg)
  lines[#lines + 1] = msg
  if logf then
    logf:write(msg, "\n")
    logf:flush()
  end
  emu.log(msg)
end

for addr, name in pairs(labels) do
  local ref
  ref = emu.addMemoryCallback(function()
    if not seen[name] then
      seen[name] = frame
      log(string.format("frame %d  %s", frame, name))
    end
    emu.removeMemoryCallback(ref, emu.callbackType.exec)
  end, emu.callbackType.exec, addr)
end

emu.addMemoryCallback(function()
  local handler = emu.read(0x00, MEM) + emu.read(0x01, MEM) * 256
  if seenHandler[handler] then
    return
  end
  seenHandler[handler] = frame
  local name = handlerNames[handler] or string.format("$%04X", handler)
  log(string.format("frame %d  actor action %s", frame, name))
end, emu.callbackType.exec, 0xE251)

emu.addEventCallback(function()
  frame = frame + 1
  local area = emu.read(0x6D, MEM)
  local lives = emu.read(0x76, MEM)
  if area ~= lastArea then
    log(string.format("frame %d  area $%02X  lives %d  timer $%02X",
      frame, area, lives, emu.read(0x63, MEM)))
    lastArea = area
  end
  if frame % 300 == 0 then
    log(string.format("frame %d  area $%02X  lives %d  pad $%02X  action $%02X  height $%02X",
      frame, area, lives, emu.read(0x28, MEM), emu.read(0x80, MEM), emu.read(0x8A, MEM)))
  end
  if frame >= FRAMES then
    log(string.format("stop  area $%02X  lives %d  timer $%02X  action $%02X  height $%02X  flags $%02X",
      area, lives, emu.read(0x63, MEM), emu.read(0x80, MEM), emu.read(0x8A, MEM), emu.read(0x84, MEM)))
    if logf then
      logf:close()
    end
    emu.stop(0)
  end
end, emu.eventType.endFrame)

emu.addEventCallback(function()
  local input = { right = true }
  local m = frame % 120
  if m < 10 then
    input.start = true
    input.right = false
  elseif m < 28 then
    input.a = true
  end
  emu.setInput(input, 0)
end, emu.eventType.inputPolled)
